"""
Generate the entanglement-sweep ablation entries for config/default_config.yaml.

Six levels (see src/evaluation/entanglement_design.py), every one with the SAME qubit count and
noise, differing only in entangling topology / depth. Each entry becomes a model name that
run_all.py and scripts/run_repeated_experiment.py can run, and whose run_id slug carries the level
so scripts/run_hypothesis_tests.py can read it back.

    python -m scripts.gen_entanglement_sweep                 # print the YAML + the run command
    python -m scripts.gen_entanglement_sweep --apply         # insert/refresh it in the config file
    python -m scripts.gen_entanglement_sweep --apply --n-qubits 8
    python -m scripts.gen_entanglement_sweep --check         # exit 1 if the config is out of date

--apply is idempotent: it only rewrites the block between the two marker comments (and creates the
block, right after the last existing ablation, the first time). A backup <config>.bak is written
once before the first change.
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.evaluation.entanglement_design import (  # noqa: E402
    DEFAULT_N_QUBITS, LEVELS, all_sweep_names, cnots_per_forward, sweep_name,
)

BEGIN = "  # >>> entanglement-sweep (generated by scripts/gen_entanglement_sweep.py; do not edit by hand) >>>"
END = "  # <<< entanglement-sweep <<<"


def build_block(n_qubits: int) -> str:
    lines = [BEGIN,
             f"  # Controlled sweep: n_qubits={n_qubits} fixed, noise_strength inherited from qgan_llm, only the",
             "  # entangling topology and depth change. CNOTs per forward pass in the trailing comments."]
    for level, topo, depth in LEVELS:
        lines += [f'  - name: "{sweep_name(level, topo, depth)}"',
                  f"    n_qubits: {n_qubits}",
                  f"    n_layers: {depth}",
                  f'    entanglement: "{topo}"',
                  f"    # level {level}: {cnots_per_forward(n_qubits, topo, depth)} CNOTs"]
    lines.append(END)
    return "\n".join(lines) + "\n"


def apply_block(text: str, block: str) -> str:
    """Return config text with the sweep block inserted or replaced."""
    nl = "\r\n" if "\r\n" in text else "\n"
    t = text.replace("\r\n", "\n")
    if BEGIN in t and END in t:
        head = t[:t.index(BEGIN)]
        tail = t[t.index(END) + len(END):].lstrip("\n")
        t = head + block + ("\n" + tail if tail and not tail.startswith("\n") else tail)
    else:
        marker = "\nqlstm_forecaster:"
        if "\nablations:" not in t or marker not in t:
            raise SystemExit("config has no 'ablations:' list followed by 'qlstm_forecaster:' -- "
                             "paste the printed block into the ablations list by hand")
        i = t.index(marker)
        t = t[:i].rstrip("\n") + "\n" + block + "\n" + t[i + 1:]   # same spacing the replace branch produces
    return t.replace("\n", nl)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n-qubits", type=int, default=DEFAULT_N_QUBITS)
    ap.add_argument("--config", default="config/default_config.yaml")
    ap.add_argument("--apply", action="store_true", help="write the block into the config file")
    ap.add_argument("--check", action="store_true", help="exit 1 if the config's block differs from what would be generated")
    ap.add_argument("--n-runs", type=int, default=6, help="seeds per level used in the printed run command")
    args = ap.parse_args()

    block = build_block(args.n_qubits)
    if args.check or args.apply:
        with open(args.config, newline="") as f:
            current = f.read()
        updated = apply_block(current, block)
        if args.check:
            sys.exit(0 if updated == current else 1)
        if updated == current:
            print(f"{args.config}: sweep block already up to date.")
        else:
            bak = args.config + ".bak"
            if not os.path.exists(bak):
                shutil.copyfile(args.config, bak)
            with open(args.config, "w", newline="") as f:
                f.write(updated)
            print(f"{args.config}: sweep block written (backup: {bak}).")
    else:
        print(block)

    names = ",".join(all_sweep_names())
    total = len(LEVELS) * args.n_runs
    print(f"\nRun it ({len(LEVELS)} levels x {args.n_runs} seeds = {total} independent runs):\n"
          f'  python -m scripts.run_repeated_experiment --model "{names}" --n-runs {args.n_runs} --base-seed 43\n'
          f"Preview first with --dry-run, check progress with --status. Then:\n"
          f"  python -m scripts.run_hypothesis_tests")


if __name__ == "__main__":
    main()
