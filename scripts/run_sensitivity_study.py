r"""Preprocessing sensitivity study (reviewer claim 6): does the headline comparison survive other defensible choices?

    python -m scripts.run_sensitivity_study --parent EXP-20261107-WINBOX-3fa9              # print the plan
    python -m scripts.run_sensitivity_study --parent EXP-... --write-configs               # + write config/variants/*.yaml

Cost-aware design. The 20-qubit primary condition takes ~48 h per run, so the sensitivity study re-runs a CHEAP proxy of
the comparison under each variant: the 12-qubit QGAN, the matched classical generator and the large classical generator
(5 seeds each; ~4 h per 12-qubit run). Each variant is its own experiment (label 'sensitivity:<variant>', parent set), so it
can never be mixed with the main study. Compare with:  python -m scripts.compare_sensitivity --parent EXP-...

Variants (src/data/variants.py): volume_winsor, robust_scaler, no_interpolation, documented_features, plus a 'baseline'
re-run of the same proxy so every variant is compared with a run made by the same code on the same machine.
The variant config adds `data_variant` to the GAN sections: checkpoints are keyed by config + seed, not by data, so without it
a baseline checkpoint would be resumed on the variant's data and the run would silently measure nothing.
"""
from __future__ import annotations

import argparse
import copy
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.data.variants import VARIANTS, default_processed_dir  # noqa: E402

PROXY_CONDITIONS = ["QGAN-LLM (12-qubit)", "Classical GAN-LLM (matched)", "Classical GAN-LLM"]
CONFIG_DIR = os.path.join("config", "variants")


def variant_config(base_cfg: dict, variant: str) -> dict:
    cfg = copy.deepcopy(base_cfg)
    cfg["data"]["processed_dir"] = default_processed_dir(variant)
    for section in ("qgan_llm", "classical_gan_llm"):
        cfg[section]["data_variant"] = variant          # changes the checkpoint fingerprint (config + seed + tag)
    return cfg


def write_variant_configs(base_path: str = "config/default_config.yaml", out_dir: str = CONFIG_DIR) -> dict:
    with open(base_path, encoding="utf-8") as f:
        base = yaml.safe_load(f)
    os.makedirs(out_dir, exist_ok=True)
    paths = {}
    for v in VARIANTS:
        p = os.path.join(out_dir, f"default_{v}.yaml")
        with open(p, "w", encoding="utf-8") as f:
            f.write(f"# GENERATED by scripts/run_sensitivity_study.py for variant '{v}'. Do not edit by hand.\n")
            yaml.safe_dump(variant_config(base, v), f, sort_keys=False)
        paths[v] = p
    return paths


def plan(parent: str, n_runs: int = 5, base_seed: int = 43) -> list:
    cond = ",".join(PROXY_CONDITIONS)
    out = []
    for v in VARIANTS:
        cfg_path = os.path.join(CONFIG_DIR, f"default_{v}.yaml")
        steps = [f"python -m scripts.prepare_data --variant {v} --processed-dir {default_processed_dir(v)}"]
        steps.append(f'.\\scripts\\run_full_study.ps1 --new-experiment --label "sensitivity:{v}" --parent-experiment {parent} '
                     f'--config {cfg_path} --conditions "{cond}" --n-runs {n_runs} --base-seed {base_seed} '
                     f'--workers 4 --no-hypothesis-tests')
        out.append({"variant": v, "config": cfg_path, "processed_dir": default_processed_dir(v), "commands": steps})
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--parent", required=True, help="experiment id of the main study these variants relate to")
    ap.add_argument("--n-runs", type=int, default=5)
    ap.add_argument("--base-seed", type=int, default=43)
    ap.add_argument("--write-configs", action="store_true")
    a = ap.parse_args()
    if a.write_configs:
        for v, p in write_variant_configs().items():
            print(f"wrote {p}")
    print("\nSensitivity plan (run the lines in order; each variant is its own experiment):\n")
    for item in plan(a.parent, a.n_runs, a.base_seed):
        print(f"# {item['variant']}")
        for c in item["commands"]:
            print("  " + c)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
